"""Render transcripts and summaries as downloadable TXT or Markdown documents."""

from __future__ import annotations

from enum import Enum

from app.schemas.summary import SummaryResponse
from app.schemas.transcription import SourceType, TranscriptionResponse


class ExportFormat(str, Enum):
    TXT = "txt"
    MD = "md"

    @property
    def media_type(self) -> str:
        return "text/markdown; charset=utf-8" if self is ExportFormat.MD else "text/plain; charset=utf-8"


def format_timestamp(seconds: float) -> str:
    total = int(seconds)
    hours, rem = divmod(total, 3600)
    minutes, secs = divmod(rem, 60)
    return f"{hours:02d}:{minutes:02d}:{secs:02d}" if hours else f"{minutes:02d}:{secs:02d}"


def render_transcript(record: TranscriptionResponse, fmt: ExportFormat) -> str:
    md = fmt is ExportFormat.MD
    lines = ["# Transcript" if md else "TRANSCRIPT", ""]
    if record.source_type is SourceType.YOUTUBE:
        meta = [("YouTube video", record.title or record.original_filename), ("URL", record.source_url or "")]
    else:
        meta = [("Source file", record.original_filename)]
    if record.transcript_source:
        meta.append(("Transcript source", record.transcript_source.value.replace("_", " ")))
    meta += [
        ("Language", record.language or "unknown"),
        ("Duration", format_timestamp(record.duration_seconds) if record.duration_seconds else "unknown"),
        ("Transcription ID", record.id),
    ]
    lines += [f"- **{k}:** {v}" if md else f"{k}: {v}" for k, v in meta]
    lines += ["", "## Full text" if md else "FULL TEXT", "", record.text or ""]
    if record.segments:
        lines += ["", "## Timestamped segments" if md else "TIMESTAMPED SEGMENTS", ""]
        for seg in record.segments:
            stamp = f"[{format_timestamp(seg.start)} - {format_timestamp(seg.end)}]"
            lines.append(f"- `{stamp}` {seg.text}" if md else f"{stamp} {seg.text}")
    return "\n".join(lines).rstrip() + "\n"


def render_summary(summary: SummaryResponse, fmt: ExportFormat) -> str:
    md = fmt is ExportFormat.MD
    c = summary.content
    title = summary.summary_type.value.replace("_", " ").title()

    def heading(text: str) -> list[str]:
        return ["", f"## {text}" if md else text.upper(), ""]

    def bullets(items: list[str]) -> list[str]:
        return [f"- {item}" for item in items]

    lines = [f"# Summary ({title})" if md else f"SUMMARY ({title.upper()})"]
    lines += heading("Overview") + [c.overview]
    if c.key_points:
        lines += heading("Key points") + bullets(c.key_points)
    if c.important_concepts:
        lines += heading("Important concepts") + bullets(
            [f"**{x.term}**: {x.explanation}" if md else f"{x.term}: {x.explanation}" for x in c.important_concepts]
        )
    if c.decisions:
        lines += heading("Decisions") + bullets(c.decisions)
    if c.suggestions:
        lines += heading("Suggestions (not confirmed)") + bullets(c.suggestions)
    if c.action_items:
        items = []
        for a in c.action_items:
            extras = [f"owner: {a.owner}" if a.owner else "", f"deadline: {a.deadline}" if a.deadline else ""]
            extra = ", ".join(e for e in extras if e)
            items.append(f"{a.task} ({extra})" if extra else a.task)
        lines += heading("Action items") + bullets(items)
    if c.follow_up_questions:
        lines += heading("Follow-up questions") + bullets(c.follow_up_questions)
    if c.uncertainties:
        lines += heading("Uncertain or unclear parts") + bullets(c.uncertainties)
    lines += ["", f"_Generated by Transmint with {summary.model}. Summary ID: {summary.id}_" if md
              else f"Generated by Transmint with {summary.model}. Summary ID: {summary.id}"]
    return "\n".join(lines).rstrip() + "\n"
